import { copyFile, mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { unified } from 'unified';
import remarkParse from 'remark-parse';
import remarkMath from 'remark-math';
import remarkRehype from 'remark-rehype';
import rehypeKatex from 'rehype-katex';
import rehypeHighlight from 'rehype-highlight';
import rehypeStringify from 'rehype-stringify';
import { renderImplicationGraph } from './render-implication-graph.mjs';

// Add { slug, title, preview } to blog-source/posts.json and write its content
// in blog-source/posts/<slug>.md. Run npm run build:blogs before committing.
// Generated HTML and math assets are committed for the existing Pages setup.
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const generatedMarker = '<!-- Generated by scripts/build-blogs.mjs. -->';
const backToTopHtml = `    <button class="blog-back-to-top" type="button" aria-label="Back to top" hidden>
      <span class="blog-back-to-top-arrow" aria-hidden="true"></span>
    </button>`;
const hash = (value) => createHash('sha256').update(value).digest('hex').slice(0, 12);
const escapeHtml = (value) => value.replace(/[&<>"']/g, (char) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
}[char]));

function fill(template, values) {
  return template.replace(/__[A-Z_]+__/g, (token) => {
    if (!(token in values)) throw new Error(`Missing template value: ${token}`);
    return values[token];
  });
}

function headingLabel(node) {
  return node.value ?? node.alt ?? node.children?.map(headingLabel).join('') ?? '';
}

function renderContents(headings) {
  if (headings.length === 0) return '';
  const list = (items) => '<ul>' + items.map(({ id, label, children }) =>
    `<li><a href="#${id}">${escapeHtml(label)}</a>${children.length ? list(children) : ''}</li>`
  ).join('') + '</ul>';
  return `          <nav class="post-contents" aria-labelledby="post-contents-label">
            <div id="post-contents-label">On this page</div>
            ${list(headings)}
          </nav>`;
}

export async function renderMarkdown(source, { omitTitle, headings } = {}) {
  const file = await unified()
    .use(remarkParse)
    .use(remarkMath)
    .use(() => (tree) => {
      const first = tree.children[0];
      const headingText = first?.children?.map((node) => node.value ?? '').join('');
      if (omitTitle && first?.type === 'heading' && first.depth === 1 && headingText === omitTitle) {
        tree.children.shift();
      }
      if (!headings) return;
      const ids = new Set();
      let section;
      for (const node of tree.children) {
        if (node.type !== 'heading' || (node.depth !== 2 && node.depth !== 3)) continue;
        const label = node.children.map(headingLabel).join('');
        const slug = label.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
        const base = slug ? `section-${slug}` : 'section';
        let id = base;
        for (let suffix = 2; ids.has(id); suffix++) id = `${base}-${suffix}`;
        ids.add(id);
        node.data = { ...node.data, hProperties: { ...node.data?.hProperties, id } };
        const entry = { id, label, children: [] };
        if (node.depth === 2) section = entry;
        if (node.depth === 3 && section) section.children.push(entry);
        else headings.push(entry);
      }
    })
    .use(remarkRehype)
    .use(rehypeKatex, { strict: 'error', trust: false })
    .use(rehypeHighlight, { detect: false })
    .use(rehypeStringify)
    .process(source);
  if (file.messages.length) throw new Error(file.messages.join('\n'));
  return String(file);
}

export async function buildBlogs({
  sourceDirectory = join(projectRoot, 'blog-source'),
  outputDirectory = projectRoot
} = {}) {
  const posts = JSON.parse(await readFile(join(sourceDirectory, 'posts.json'), 'utf8'));
  if (!Array.isArray(posts)) throw new Error('posts.json must contain an array');
  const slugs = new Set();
  const articles = [];

  // Render and validate every post before replacing any published files.
  for (const post of posts) {
    if (!post || typeof post.slug !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(post.slug)) {
      throw new Error('Each post needs a lowercase, hyphenated slug');
    }
    if (slugs.has(post.slug)) throw new Error(`Duplicate post slug: ${post.slug}`);
    slugs.add(post.slug);
    for (const field of ['title', 'preview']) {
      if (typeof post[field] !== 'string' || !post[field].trim()) {
        throw new Error(`${post.slug} needs a ${field}`);
      }
    }
    if (post.hero && (!/^assets\/[a-z0-9/_-]+\.(?:png|jpe?g|webp|svg)$/i.test(post.hero) || typeof post.heroAlt !== 'string' || !post.heroAlt.trim())) {
      throw new Error(`${post.slug} needs a local illustration path and alt text`);
    }
    if ((post.heroWidth !== undefined || post.heroHeight !== undefined) &&
        (!Number.isInteger(post.heroWidth) || post.heroWidth <= 0 || !Number.isInteger(post.heroHeight) || post.heroHeight <= 0)) {
      throw new Error(`${post.slug} needs positive illustration dimensions`);
    }
    if (post.hero) await readFile(join(projectRoot, post.hero));
    if (post.layout === 'grh-implications') {
      const filename = post.source ?? `${post.slug}.json`;
      if (typeof filename !== 'string' || !/^[a-z0-9][a-z0-9._-]*\.json$/i.test(filename)) {
        throw new Error(`${post.slug} needs a JSON filename without directory components`);
      }
      const source = await readFile(join(sourceDirectory, 'posts', filename), 'utf8');
      articles.push({ ...post, graph: renderImplicationGraph(source) });
      continue;
    }
    if (post.layout !== undefined) throw new Error(`${post.slug} has an unknown layout: ${post.layout}`);
    const filename = post.source ?? `${post.slug}.md`;
    if (typeof filename !== 'string' || !/^[a-z0-9][a-z0-9._-]*\.md$/i.test(filename)) {
      throw new Error(`${post.slug} needs a Markdown filename without directory components`);
    }
    const source = await readFile(join(sourceDirectory, 'posts', filename), 'utf8');
    const headings = post.contents ? [] : undefined;
    const html = await renderMarkdown(source, { omitTitle: post.title, headings });
    articles.push({ ...post, html, contentsHtml: headings ? renderContents(headings) : '' });
  }

  const katexRoot = dirname(dirname(require.resolve('katex')));
  let mathCss = await readFile(join(katexRoot, 'dist/katex.min.css'), 'utf8');
  // Retain WOFF2 sources; unused WOFF/TTF copies are not deployed.
  mathCss = mathCss.replace(/src:([^;}]+)/g, (declaration, sources) => {
    const woff2 = sources.match(/url\([^)]*\.woff2\)\s*format\([^)]*\)/);
    return woff2 ? `src:${woff2[0]}` : declaration;
  });
  const blogCss = await readFile(join(projectRoot, 'assets/blog.css'), 'utf8');
  const backToTopJs = await readFile(join(projectRoot, 'assets/blog-back-to-top.js'), 'utf8');
  const versions = {
    __BLOG_VERSION__: hash(blogCss),
    __MATH_VERSION__: hash(mathCss),
    __BACK_TO_TOP_VERSION__: hash(backToTopJs)
  };
  const postTemplate = await readFile(join(projectRoot, 'blog-source/templates/post.html'), 'utf8');
  const indexTemplate = await readFile(join(projectRoot, 'blog-source/templates/index.html'), 'utf8');
  const [graphTemplate, graphCss, graphJs] = articles.some(post => post.graph) ? await Promise.all([
    readFile(join(projectRoot, 'blog-source/templates/grh-implications.html'), 'utf8'),
    readFile(join(projectRoot, 'assets/grh-implications.css'), 'utf8'),
    readFile(join(projectRoot, 'assets/grh-implications.js'), 'utf8')
  ]) : [];
  const home = await readFile(join(projectRoot, 'index.html'), 'utf8');
  let header = home.match(/      <header class="site-header">[\s\S]*?<\/header>/)?.[0];
  if (!header || !header.includes('<a href="blogs.html">Blogs</a>')) {
    throw new Error('The homepage header must contain the Blogs navigation link');
  }
  header = header.replaceAll(' aria-current="page"', '')
    .replace('<a href="blogs.html">Blogs</a>', '<a href="blogs.html" aria-current="page">Blogs</a>');

  const entries = articles.map((post) =>
    `        <article class="blog-entry">\n          <h3><a href="blogs/${post.slug}.html">${escapeHtml(post.title)}</a></h3>\n          <p>${escapeHtml(post.preview)}</p>\n        </article>`
  ).join('\n');
  const index = fill(indexTemplate, { ...versions, __SITE_HEADER__: header, __BLOG_ENTRIES__: entries });
  const pages = articles.map((post) => {
    const metadata = {
      ...versions,
      __TITLE__: escapeHtml(post.title),
      __DESCRIPTION__: escapeHtml(post.preview),
      __BACK_TO_TOP_HTML__: backToTopHtml,
      __HERO_HTML__: post.hero
        ? `          <figure class="blog-illustration"><img src="../${escapeHtml(post.hero)}" alt="${escapeHtml(post.heroAlt)}"${post.heroWidth ? ` width="${post.heroWidth}" height="${post.heroHeight}"` : ''} decoding="async"></figure>`
        : ''
    };
    return {
      slug: post.slug,
      html: post.graph ? fill(graphTemplate, {
        ...metadata,
        __GRAPH_CSS_VERSION__: hash(graphCss),
        __GRAPH_JS_VERSION__: hash(graphJs),
        __GRAPH_DATA__: post.graph.data,
        __GRAPH_STATEMENTS__: post.graph.statements
      }) : fill(postTemplate, {
        ...metadata,
        __CONTENTS_HTML__: post.contentsHtml,
        __ARTICLE_HTML__: post.html
      })
    };
  });

  const postDirectory = join(outputDirectory, 'blogs');
  const assetDirectory = join(outputDirectory, 'assets/katex');
  await mkdir(postDirectory, { recursive: true });
  await mkdir(join(assetDirectory, 'fonts'), { recursive: true });
  await writeFile(join(assetDirectory, 'katex.min.css'), mathCss);
  await copyFile(join(katexRoot, 'LICENSE'), join(assetDirectory, 'LICENSE'));
  for (const font of await readdir(join(katexRoot, 'dist/fonts'))) {
    if (font.endsWith('.woff2')) {
      await copyFile(join(katexRoot, 'dist/fonts', font), join(assetDirectory, 'fonts', font));
    }
  }
  if (resolve(outputDirectory) !== projectRoot) {
    await writeFile(join(outputDirectory, 'assets/blog.css'), blogCss);
    await writeFile(join(outputDirectory, 'assets/blog-back-to-top.js'), backToTopJs);
    if (graphTemplate) {
      await writeFile(join(outputDirectory, 'assets/grh-implications.css'), graphCss);
      await writeFile(join(outputDirectory, 'assets/grh-implications.js'), graphJs);
    }
    for (const post of articles) {
      if (post.hero) {
        await mkdir(dirname(join(outputDirectory, post.hero)), { recursive: true });
        await copyFile(join(projectRoot, post.hero), join(outputDirectory, post.hero));
      }
    }
  }
  for (const page of pages) await writeFile(join(postDirectory, `${page.slug}.html`), page.html);
  await writeFile(join(outputDirectory, 'blogs.html'), index);

  // Remove obsolete generated posts while preserving hand-written files.
  for (const filename of await readdir(postDirectory)) {
    if (!filename.endsWith('.html') || slugs.has(filename.slice(0, -5))) continue;
    const path = join(postDirectory, filename);
    if ((await readFile(path, 'utf8')).includes(generatedMarker)) await unlink(path);
  }
  return { count: articles.length, index: join(outputDirectory, 'blogs.html') };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await buildBlogs();
  console.log(`Built Blogs with ${result.count} post(s).`);
}
